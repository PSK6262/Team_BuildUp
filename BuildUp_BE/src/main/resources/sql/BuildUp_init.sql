-- 1. USER_ROLES (회원 권한 등급 마스터)
CREATE TABLE USER_ROLES (
    ROLE_CODE          NUMBER        NOT NULL, -- 권한 코드 식별자 (1: 일반회원, 7: 탈퇴회원, 8: 제재회원, 9: 관리자 등)
    ROLE_NAME          VARCHAR2(50)  NOT NULL, -- 권한 명칭
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (ROLE_CODE)
);

-- 2. TEAMS (축구 구단 기본 정보)
CREATE TABLE TEAMS (
    TEAM_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 구단 식별자
    TEAM_NAME          VARCHAR2(100) NOT NULL, -- 구단 명칭
    TEAM_NAME_KOR      VARCHAR2(100),          -- 구단 명칭 한글명
    HOME_GROUND        VARCHAR2(100) NOT NULL, -- 구단 홈 경기장 명칭
    HOME_GROUND_KOR    VARCHAR2(100),          -- 구단 홈 경기장 명칭 한글명
    FOUNDED_YEAR       DATE          NOT NULL, -- 구단 창단 연도
    UPDATED_AT         TIMESTAMP,              -- 구단 정보 수정 일시
    EMBLEM_URL         VARCHAR2(500),          -- 구단 엠블럼 이미지 URL
    ANTHEM_URL         VARCHAR2(500),          -- 구단가 및 응원가 URL
    HISTORY            CLOB,                   -- 구단 역사 및 소개
    CONSTRAINT PK_TEAMS PRIMARY KEY (TEAM_ID),
    CONSTRAINT UQ_TEAMS_TEAM_NAME UNIQUE (TEAM_NAME)
);

-- 3. STAFF_ROLES (스태프 직책 마스터)
CREATE TABLE STAFF_ROLES (
    STAFF_ROLE_ID      NUMBER        NOT NULL, -- 스태프 직책 식별자
    ROLE_NAME          VARCHAR2(50)  NOT NULL, -- 스태프 직책 명칭 (감독, 코치 등)
    CONSTRAINT PK_STAFF_ROLES PRIMARY KEY (STAFF_ROLE_ID)
);

-- 4. CATEGORY (게시글 분류 카테고리)
CREATE TABLE CATEGORY (
    CATEGORY_ID        NUMBER        NOT NULL, -- 게시글 카테고리 식별자
    CATEGORY_TYPE      VARCHAR2(50)  NOT NULL, -- 카테고리 명칭 (자유, 질문, 뉴스 등)
    CONSTRAINT PK_CATEGORY PRIMARY KEY (CATEGORY_ID)
);

-- 5. EVENT_TYPE (경기 이벤트 유형 코드)
CREATE TABLE EVENT_TYPE (
    EVENT_TYPE_CODE    NUMBER        NOT NULL, -- 이벤트 유형 코드 식별자
    EVENT_TYPE_NAME    VARCHAR2(50)  NOT NULL, -- 이벤트 유형 명칭 (골, 경고, 퇴장 등)
    EVENT_ICON_URL     VARCHAR2(500),          -- 이벤트 표시 아이콘 이미지 URL
    CONSTRAINT PK_EVENT_TYPE PRIMARY KEY (EVENT_TYPE_CODE)
);

-- --------------------------------------------------------------------
-- [2. 회원 및 회원 통계]
-- --------------------------------------------------------------------

-- 6. USERS (회원 기본 정보)
CREATE TABLE USERS (
    USER_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 회원 식별자
    LOGIN_ID           VARCHAR2(50)  NOT NULL, -- 로그인 아이디
    PASSWORD           VARCHAR2(255) NOT NULL, -- 비밀번호 (암호화)
    NICKNAME           VARCHAR2(50)  NOT NULL, -- 회원 닉네임
    EMAIL              VARCHAR2(100) NOT NULL, -- 회원 이메일
    FAVORITE_TEAM_ID   NUMBER,                 -- 선호 구단 식별자 (NULL 허용)
    ROLE_CODE          NUMBER        NOT NULL, -- 회원 권한 코드 (NUMBER)
    POINT              NUMBER DEFAULT 100 NOT NULL, -- 보유 포인트 잔액 (기본값 100)
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 회원 가입 일시
    UPDATED_AT         TIMESTAMP,              -- 회원 정보 수정 일시
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_LOGIN_ID UNIQUE (LOGIN_ID),
    CONSTRAINT UQ_USERS_NICKNAME UNIQUE (NICKNAME),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_POINT CHECK (POINT >= 0),
    CONSTRAINT FK_USERS_FAVORITE_TEAM FOREIGN KEY (FAVORITE_TEAM_ID) REFERENCES TEAMS(TEAM_ID),
    CONSTRAINT FK_USERS_ROLE_CODE FOREIGN KEY (ROLE_CODE) REFERENCES USER_ROLES(ROLE_CODE)
);

-- 7. USER_PREDICTS (회원의 승부예측 전적 및 승률 요약 통계 - 1:1)
CREATE TABLE USER_PREDICTS (
    USER_ID            NUMBER        NOT NULL, -- 회원 식별자
    PREDICT_WIN        NUMBER DEFAULT 0 NOT NULL, -- 승부예측 성공 횟수
    PREDICT_TOTAL      NUMBER DEFAULT 0 NOT NULL, -- 승부예측 총 참여 횟수
    UPDATED_AT         TIMESTAMP,              -- 통계 갱신 일시
    CONSTRAINT PK_USER_PREDICTS PRIMARY KEY (USER_ID),
    CONSTRAINT FK_USER_PREDICTS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);

-- 7-1. EMAIL_VERIFICATIONS (이메일 인증 및 가입 대기)
CREATE TABLE EMAIL_VERIFICATIONS (
    AUTH_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    EMAIL              VARCHAR2(100) NOT NULL,
    AUTH_KEY           VARCHAR2(100) NOT NULL,
    AUTH_TYPE          VARCHAR2(20)  NOT NULL, -- 'SIGNUP', 'PASSWORD_RESET'
    PAYLOAD            CLOB,                   -- 가입 정보 JSON
    EXPIRED_AT         TIMESTAMP     NOT NULL, -- 만료 일시
    IS_VERIFIED        CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EMAIL_VERIFICATIONS PRIMARY KEY (AUTH_ID),
    CONSTRAINT UQ_EMAIL_VERIF_KEY UNIQUE (AUTH_KEY)
);

-- --------------------------------------------------------------------
-- [3. 구단 상세 / 스태프 / 선수 / 경기]
-- --------------------------------------------------------------------

-- 8. TEAM_STATS (구단 시즌 성적 및 순위 통계 - 1:1)
CREATE TABLE TEAM_STATS (
    TEAM_ID            NUMBER        NOT NULL, -- 구단 식별자
    CURRENT_RANK       NUMBER,                 -- 시즌 현재 순위
    MATCHES_PLAYED     NUMBER DEFAULT 0 NOT NULL, -- 치른 경기 수
    WINS               NUMBER DEFAULT 0 NOT NULL, -- 승리 횟수
    DRAWS              NUMBER DEFAULT 0 NOT NULL, -- 무승부 횟수
    LOSSES             NUMBER DEFAULT 0 NOT NULL, -- 패배 횟수
    POINTS             NUMBER DEFAULT 0 NOT NULL, -- 획득 승점
    GOALS_FOR          NUMBER DEFAULT 0 NOT NULL, -- 총 득점 수
    GOALS_AGAINST      NUMBER DEFAULT 0 NOT NULL, -- 총 실점 수
    GOAL_DIFF          NUMBER DEFAULT 0 NOT NULL, -- 골득실차
    YELLOW_CARDS       NUMBER DEFAULT 0 NOT NULL, -- 경고 누적 수
    RED_CARDS          NUMBER DEFAULT 0 NOT NULL, -- 퇴장 누적 수
    UPDATED_AT         TIMESTAMP,              -- 기록 갱신 일시
    CONSTRAINT PK_TEAM_STATS PRIMARY KEY (TEAM_ID),
    CONSTRAINT FK_TEAM_STATS_TEAM_ID FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID)
);

-- 9. STAFFS (구단 스태프 기본 정보)
CREATE TABLE STAFFS (
    STAFF_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 스태프 식별자
    NAME               VARCHAR2(100) NOT NULL, -- 스태프 이름
    NAME_KOR           VARCHAR2(100),          -- 스태프 이름 한글명
    NATIONALITY        VARCHAR2(50),           -- 스태프 국적
    NATIONALITY_KOR    VARCHAR2(50),           -- 스태프 국적 한글명
    TEAM_ID            NUMBER        NOT NULL, -- 소속 구단 식별자
    STAFF_ROLE_ID      NUMBER        NOT NULL, -- 직책 식별자
    CONSTRAINT PK_STAFFS PRIMARY KEY (STAFF_ID),
    CONSTRAINT FK_STAFFS_TEAM_ID FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID),
    CONSTRAINT FK_STAFFS_STAFF_ROLE_ID FOREIGN KEY (STAFF_ROLE_ID) REFERENCES STAFF_ROLES(STAFF_ROLE_ID)
);

-- 10. PLAYERS (축구 선수 기본 정보)
CREATE TABLE PLAYERS (
    PLAYER_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 선수 식별자
    NAME               VARCHAR2(100) NOT NULL, -- 선수 이름
    NAME_KOR           VARCHAR2(100),          -- 선수 이름 한글명
    MAIN_POSITION      VARCHAR2(20)  NOT NULL, -- 주 포지션 (FW, MF, DF, GK)
    DETAIL_POSITION    VARCHAR2(20),           -- 상세 포지션 공식 약어 (CB, LB, CDM, CAM, ST 등)
    NATIONALITY        VARCHAR2(50),           -- 선수 국적
    NATIONALITY_KOR    VARCHAR2(50),           -- 선수 국적 한글명
    TEAM_ID            NUMBER        NOT NULL, -- 소속 구단 식별자
    CONSTRAINT PK_PLAYERS PRIMARY KEY (PLAYER_ID),
    CONSTRAINT FK_PLAYERS_TEAM_ID FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID)
);

-- 11. PLAYER_STATS (선수 시즌 개인 기록 및 부상/징계 상태 - 1:1)
CREATE TABLE PLAYER_STATS (
    PLAYER_ID          NUMBER        NOT NULL, -- 선수 식별자
    GOALS              NUMBER DEFAULT 0 NOT NULL, -- 시즌 득점 수
    ASSISTS            NUMBER DEFAULT 0 NOT NULL, -- 시즌 도움 수
    MOM_COUNT          NUMBER DEFAULT 0 NOT NULL, -- 경기 최우수선수(MOM) 선정 횟수
    YELLOW_CARDS       NUMBER DEFAULT 0 NOT NULL, -- 경고 누적 수
    RED_CARDS          NUMBER DEFAULT 0 NOT NULL, -- 퇴장 누적 수
    IS_INJURED         VARCHAR2(1) DEFAULT 'N' NOT NULL, -- 부상 여부 (Y/N)
    IS_SUSPENDED       VARCHAR2(1) DEFAULT 'N' NOT NULL, -- 출장 정지 징계 여부 (Y/N)
    INJURY_NOTE        CLOB,                   -- 부상 상세 메모 및 결장 사유
    CONSTRAINT PK_PLAYER_STATS PRIMARY KEY (PLAYER_ID),
    CONSTRAINT CK_PLAYER_STATS_INJURED CHECK (IS_INJURED IN ('Y', 'N')),
    CONSTRAINT CK_PLAYER_STATS_SUSPEND CHECK (IS_SUSPENDED IN ('Y', 'N')),
    CONSTRAINT FK_PLAYER_STATS_PLAYER_ID FOREIGN KEY (PLAYER_ID) REFERENCES PLAYERS(PLAYER_ID)
);

-- 12. MATCHES (축구 경기 일정 및 스코어 결과)
CREATE TABLE MATCHES (
    MATCH_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 경기 식별자
    HOME_TEAM_ID       NUMBER        NOT NULL, -- 홈팀 식별자
    AWAY_TEAM_ID       NUMBER        NOT NULL, -- 원정팀 식별자
    HOME_SCORE         NUMBER,                 -- 홈팀 최종 득점 수 (경기 전 NULL)
    AWAY_SCORE         NUMBER,                 -- 원정팀 최종 득점 수 (경기 전 NULL)
    STATUS             VARCHAR2(20)  NOT NULL, -- 경기 상태 (SCHEDULED, LIVE, FINISHED, CANCELLED 등)
    MATCH_DATE         TIMESTAMP     NOT NULL, -- 경기 시작 일시
    ENDED_AT           TIMESTAMP,              -- 경기가 끝난 시간 (종료 전 NULL)
    NOTICE             CLOB,                   -- 경기 중단, 연기, 취소 등 발생 시 알림
    CONSTRAINT PK_MATCHES PRIMARY KEY (MATCH_ID),
    CONSTRAINT CK_MATCHES_TEAMS_DIFF CHECK (HOME_TEAM_ID != AWAY_TEAM_ID),
    CONSTRAINT FK_MATCHES_HOME_TEAM FOREIGN KEY (HOME_TEAM_ID) REFERENCES TEAMS(TEAM_ID),
    CONSTRAINT FK_MATCHES_AWAY_TEAM FOREIGN KEY (AWAY_TEAM_ID) REFERENCES TEAMS(TEAM_ID)
);

-- 13. MATCH_LINEUPS (경기별 양 팀 출전 선수 명단 및 포지션)
CREATE TABLE MATCH_LINEUPS (
    LINEUP_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 라인업 식별자
    MATCH_ID           NUMBER        NOT NULL, -- 대상 경기 식별자
    TEAM_ID            NUMBER        NOT NULL, -- 소속 구단 식별자
    PLAYER_ID          NUMBER        NOT NULL, -- 출전 선수 식별자
    MATCH_POSITION     VARCHAR2(20)  NOT NULL, -- 경기 소화 포지션
    IS_STARTER         VARCHAR2(1)   NOT NULL, -- 선발 출전 여부 (Y: 선발 / N: 교체명단)
    CONSTRAINT PK_MATCH_LINEUPS PRIMARY KEY (LINEUP_ID),
    CONSTRAINT CK_MATCH_LINEUPS_STARTER CHECK (IS_STARTER IN ('Y', 'N')),
    CONSTRAINT FK_MATCH_LINEUPS_MATCH FOREIGN KEY (MATCH_ID) REFERENCES MATCHES(MATCH_ID),
    CONSTRAINT FK_MATCH_LINEUPS_TEAM FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID),
    CONSTRAINT FK_MATCH_LINEUPS_PLAYER FOREIGN KEY (PLAYER_ID) REFERENCES PLAYERS(PLAYER_ID)
);

-- 14. MATCH_EVENTS (경기 타임라인 상세 이벤트 기록)
CREATE TABLE MATCH_EVENTS (
    EVENT_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 경기 이벤트 식별자
    MATCH_ID           NUMBER        NOT NULL, -- 대상 경기 식별자
    TEAM_ID            NUMBER        NOT NULL, -- 해당 이벤트 발생 구단 식별자
    EVENT_TIME         NUMBER        NOT NULL, -- 이벤트 발생 시간 (초 또는 분 단위)
    EVENT_TYPE         NUMBER        NOT NULL, -- 이벤트 유형 코드 식별자
    PLAYER_ID          NUMBER        NOT NULL, -- 주요 행동 선수 식별자
    ASSIST_PLAYER_ID   NUMBER,                 -- 도움 선수 식별자 (없으면 NULL)
    CONSTRAINT PK_MATCH_EVENTS PRIMARY KEY (EVENT_ID),
    CONSTRAINT FK_MATCH_EVENTS_MATCH FOREIGN KEY (MATCH_ID) REFERENCES MATCHES(MATCH_ID),
    CONSTRAINT FK_MATCH_EVENTS_TEAM FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID),
    CONSTRAINT FK_MATCH_EVENTS_TYPE FOREIGN KEY (EVENT_TYPE) REFERENCES EVENT_TYPE(EVENT_TYPE_CODE),
    CONSTRAINT FK_MATCH_EVENTS_PLAYER FOREIGN KEY (PLAYER_ID) REFERENCES PLAYERS(PLAYER_ID),
    CONSTRAINT FK_MATCH_EVENTS_ASSIST FOREIGN KEY (ASSIST_PLAYER_ID) REFERENCES PLAYERS(PLAYER_ID)
);

-- --------------------------------------------------------------------
-- [4. 커스텀 팀 및 AI 매치 시뮬레이션]
-- --------------------------------------------------------------------

-- 15. CUSTOM_TEAMS (회원이 생성한 나만의 팀 정보 - 1:1)
CREATE TABLE CUSTOM_TEAMS (
    CUSTOM_TEAM_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 커스텀 팀 식별자
    USER_ID            NUMBER        NOT NULL, -- 구단주 회원 식별자 (1:1 관계 보장)
    TEAM_NAME          VARCHAR2(100) NOT NULL, -- 유저가 설정한 팀 명칭
    FORMATION          VARCHAR2(20)  NOT NULL, -- 적용 포메이션 (예: 4-3-3, 4-4-2)
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 커스텀 팀 생성 일시
    CONSTRAINT PK_CUSTOM_TEAMS PRIMARY KEY (CUSTOM_TEAM_ID),
    CONSTRAINT UQ_CUSTOM_TEAMS_USER_ID UNIQUE (USER_ID),
    CONSTRAINT FK_CUSTOM_TEAMS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);

-- 16. CUSTOM_SQUADS (회원이 생성한 나만의 팀 엔트리 구성 및 배치 정보)
CREATE TABLE CUSTOM_SQUADS (
    SQUAD_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 스쿼드 슬롯 식별자
    CUSTOM_TEAM_ID     NUMBER        NOT NULL, -- 소속 커스텀 팀 식별자
    PLAYER_ID          NUMBER        NOT NULL, -- 배치된 선수 식별자
    POSITION_NO        NUMBER        NOT NULL, -- 포메이션 내 배치 슬롯 번호 (1~11)
    CONSTRAINT PK_CUSTOM_SQUADS PRIMARY KEY (SQUAD_ID),
    CONSTRAINT UQ_CUSTOM_SQUADS_SLOT UNIQUE (CUSTOM_TEAM_ID, POSITION_NO),
    CONSTRAINT UQ_CUSTOM_SQUADS_PLAYER UNIQUE (CUSTOM_TEAM_ID, PLAYER_ID),
    CONSTRAINT FK_CUSTOM_SQUADS_TEAM FOREIGN KEY (CUSTOM_TEAM_ID) REFERENCES CUSTOM_TEAMS(CUSTOM_TEAM_ID),
    CONSTRAINT FK_CUSTOM_SQUADS_PLAYER FOREIGN KEY (PLAYER_ID) REFERENCES PLAYERS(PLAYER_ID)
);

-- 17. AI_MATCHES (AI 가상 대결 결과 및 AI의 경기 평가 기록)
CREATE TABLE AI_MATCHES (
    AI_MATCH_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- AI 경기 식별자
    HOME_TEAM_ID       NUMBER        NOT NULL, -- 신청한 내 커스텀 팀 식별자
    AWAY_TEAM_ID       NUMBER        NOT NULL, -- 대결 상대 커스텀 팀 식별자
    HOME_SCORE         NUMBER        NOT NULL, -- 홈팀 시뮬레이션 점수
    AWAY_SCORE         NUMBER        NOT NULL, -- 원정팀 시뮬레이션 점수
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- AI 경기 진행 일시
    AI_REVIEW          CLOB,                   -- AI 경기 관전평 및 시뮬레이션 요약
    CONSTRAINT PK_AI_MATCHES PRIMARY KEY (AI_MATCH_ID),
    CONSTRAINT CK_AI_MATCHES_DIFF CHECK (HOME_TEAM_ID != AWAY_TEAM_ID),
    CONSTRAINT FK_AI_MATCHES_HOME_TEAM FOREIGN KEY (HOME_TEAM_ID) REFERENCES CUSTOM_TEAMS(CUSTOM_TEAM_ID),
    CONSTRAINT FK_AI_MATCHES_AWAY_TEAM FOREIGN KEY (AWAY_TEAM_ID) REFERENCES CUSTOM_TEAMS(CUSTOM_TEAM_ID)
);

