-- 18. POSTS (커뮤니티 게시글 정보)
CREATE TABLE POSTS (
    POST_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 게시글 식별자
    USER_ID            NUMBER        NOT NULL, -- 작성자 회원 식별자
    CATEGORY_ID        NUMBER        NOT NULL, -- 게시글 카테고리 식별자
    TEAM_ID            NUMBER,                 -- 구단 카테고리 필터 식별자 (자유글은 NULL)
    TITLE              VARCHAR2(255) NOT NULL, -- 게시글 제목
    VIEW_COUNT         NUMBER DEFAULT 0 NOT NULL, -- 게시글 조회수
    LIKE_COUNT         NUMBER DEFAULT 0 NOT NULL, -- 게시글 추천수
    IS_BLIND           VARCHAR2(1) DEFAULT 'N' NOT NULL, -- 블라인드 제재 여부 (Y/N)
    IS_DELETED         VARCHAR2(1) DEFAULT 'N' NOT NULL, -- 작성자 삭제 여부 (Y/N)
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 게시글 작성 일시
    UPDATED_AT         TIMESTAMP,              -- 게시글 수정 일시
    CONTENT            CLOB          NOT NULL, -- 게시글 본문 내용
    CONSTRAINT PK_POSTS PRIMARY KEY (POST_ID),
    CONSTRAINT CK_POSTS_IS_BLIND CHECK (IS_BLIND IN ('Y', 'N')),
    CONSTRAINT CK_POSTS_IS_DELETED CHECK (IS_DELETED IN ('Y', 'N')),
    CONSTRAINT FK_POSTS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_POSTS_TEAM_ID FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID),
    CONSTRAINT FK_POSTS_CATEGORY_ID FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID)
);

-- 19. COMMENTS (게시글 댓글 및 대댓글)
CREATE TABLE COMMENTS (
    COMMENT_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 댓글 식별자
    POST_ID            NUMBER        NOT NULL, -- 대상 게시글 식별자
    USER_ID            NUMBER        NOT NULL, -- 댓글 작성자 회원 식별자
    P_COMMENT_ID       NUMBER,                 -- 부모 댓글 식별자 (원댓글인 경우 NULL)
    IS_BLIND           VARCHAR2(1) DEFAULT 'N' NOT NULL, -- 블라인드 제재 여부 (Y/N)
    IS_DELETED         VARCHAR2(1) DEFAULT 'N' NOT NULL, -- 작성자 삭제 여부 (Y/N)
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 댓글 작성 일시
    UPDATED_AT         TIMESTAMP,              -- 댓글 수정 일시
    CONTENT            CLOB          NOT NULL, -- 댓글 내용
    CONSTRAINT PK_COMMENTS PRIMARY KEY (COMMENT_ID),
    CONSTRAINT CK_COMMENTS_IS_BLIND CHECK (IS_BLIND IN ('Y', 'N')),
    CONSTRAINT CK_COMMENTS_IS_DELETED CHECK (IS_DELETED IN ('Y', 'N')),
    CONSTRAINT FK_COMMENTS_POST_ID FOREIGN KEY (POST_ID) REFERENCES POSTS(POST_ID),
    CONSTRAINT FK_COMMENTS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_COMMENTS_PARENT FOREIGN KEY (P_COMMENT_ID) REFERENCES COMMENTS(COMMENT_ID)
);

-- 20. POST_LIKES (게시글 추천 내역 - 복합 PK)
CREATE TABLE POST_LIKES (
    USER_ID            NUMBER        NOT NULL, -- 추천 누른 회원 식별자
    POST_ID            NUMBER        NOT NULL, -- 추천 대상 게시글 식별자
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 게시글 추천 일시
    CONSTRAINT PK_POST_LIKES PRIMARY KEY (USER_ID, POST_ID),
    CONSTRAINT FK_POST_LIKES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_POST_LIKES_POST FOREIGN KEY (POST_ID) REFERENCES POSTS(POST_ID)
);

-- 21. COMMENT_LIKES (댓글 추천 내역 - 복합 PK)
CREATE TABLE COMMENT_LIKES (
    USER_ID            NUMBER        NOT NULL, -- 추천 누른 회원 식별자
    COMMENT_ID         NUMBER        NOT NULL, -- 추천 대상 댓글 식별자
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 댓글 추천 일시
    CONSTRAINT PK_COMMENT_LIKES PRIMARY KEY (USER_ID, COMMENT_ID),
    CONSTRAINT FK_COMMENT_LIKES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_COMMENT_LIKES_COMMENT FOREIGN KEY (COMMENT_ID) REFERENCES COMMENTS(COMMENT_ID)
);

