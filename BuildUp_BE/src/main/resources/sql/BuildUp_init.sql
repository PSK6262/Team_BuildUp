-- --------------------------------------------------------------------

-- 22. PREDICTIONS (회원의 경기별 개별 승부예측 참여 이력)
CREATE TABLE PREDICTIONS (
    PREDICTION_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 승부예측 식별자
    USER_ID            NUMBER        NOT NULL, -- 참여 회원 식별자
    MATCH_ID           NUMBER        NOT NULL, -- 대상 경기 식별자
    PREDICT_RESULT     VARCHAR2(20)  NOT NULL, -- 예측 결과 (HOME, DRAW, AWAY)
    IS_SUCCESS         VARCHAR2(1),            -- 적중 여부 (Y: 성공, N: 실패, C: 경기취소/무효, 경기 전 NULL)
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 예측 제출 일시
    CONSTRAINT PK_PREDICTIONS PRIMARY KEY (PREDICTION_ID),
    CONSTRAINT UQ_PREDICTIONS_USER_MATCH UNIQUE (USER_ID, MATCH_ID),
    CONSTRAINT CK_PREDICTIONS_SUCCESS CHECK (IS_SUCCESS IS NULL OR IS_SUCCESS IN ('Y', 'N', 'C')),
    CONSTRAINT FK_PREDICTIONS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_PREDICTIONS_MATCH FOREIGN KEY (MATCH_ID) REFERENCES MATCHES(MATCH_ID)
);

-- 23. POINT_HISTORY (회원 포인트 적립 및 차감 변동 이력)
CREATE TABLE POINT_HISTORY (
    POINT_HISTORY_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL, -- 포인트 변동 이력 식별자
    USER_ID            NUMBER        NOT NULL, -- 대상 회원 식별자
    PREDICTION_ID      NUMBER,                 -- 관련 승부예측 식별자 (기타 사유는 NULL)
    AMOUNT             NUMBER        NOT NULL, -- 변동 포인트 (+500, -300 등)
    BALANCE_AFTER      NUMBER        NOT NULL, -- 변동 후 잔여 포인트
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 내역 발생 일시
    DESCRIPTION        CLOB          NOT NULL, -- 변동 사유 내용
    CONSTRAINT PK_POINT_HISTORY PRIMARY KEY (POINT_HISTORY_ID),
    CONSTRAINT FK_POINT_HISTORY_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_POINT_HISTORY_PRED FOREIGN KEY (PREDICTION_ID) REFERENCES PREDICTIONS(PREDICTION_ID)
);

